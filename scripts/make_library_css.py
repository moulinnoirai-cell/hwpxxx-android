"""Builds assets/library.css from the approved design fragment.

The design is scoped to #hwpxxx-library-complete-intro and wrapped in a fake
phone frame. The product keeps the rules for the library, intro, and dialogs,
re-scopes them to #hwp-app, and drops preview chrome, discarded variants
(cloud/X/shield art, two-slide intro) and the mock editor.
"""
import re, sys

src, out = sys.argv[1], sys.argv[2]
css = open(src, encoding='utf-8').read()
css = css[css.index('#hwpxxx-library-complete-intro{'):]

DROP = re.compile(r'''hw-preview|hw-safe|hw-local|hw-core-chip|hw-security-symbol|hw-security-subtitle|hw-security-line
|hw-centered|hw-cloud|hw-art-|hw-flat-frame|hw-flat-core|hw-flat-badge|hw-flat-sheet|hw-flat-blocker|hw-flat-ban
|hw-edit|hw-editor|hw-paper|hw-read-|hw-panel-row|hw-benefit|hw-circle-mode-compact|hw-mini|hw-theme\{|hw-menu-dialog
|hw-menu-title|hw-menu-name|hw-save-extension|hw-file-name|hw-settings-note|hw-permission-state|hw-phone\[|\.hw-phone\{color-scheme
|hw-screen\{|hw-sr\{|cursor-interaction''', re.X)

rules = []
depth = 0
buf = ''
for ch in css:
    buf += ch
    if ch == '{':
        depth += 1
    elif ch == '}':
        depth -= 1
        if depth == 0:
            rules.append(buf.strip())
            buf = ''

kept = []
for r in rules:
    head = r[:r.index('{')]
    if r.startswith('@media') or r.startswith('@keyframes'):
        inner = r[r.index('{') + 1:-1]
        parts = re.findall(r'[^{}]+\{[^{}]*\}', inner)
        parts = [p for p in parts if not DROP.search(p[:p.index('{')])] if r.startswith('@media') else parts
        if parts:
            kept.append(head + '{' + ''.join(parts) + '}')
        continue
    if DROP.search(head):
        continue
    kept.append(r)

text = '\n'.join(kept)
text = text.replace('#hwpxxx-library-complete-intro .hw-phone ', '#hwp-app ')
text = text.replace('#hwpxxx-library-complete-intro', '#hwp-app')
text = text.replace('hw-preview-permission-glow', 'hw-permission-glow')
# The phone frame becomes the app root: keep its tokens (aliased to the product theme), drop its size and border.
text = re.sub(r'#hwp-app \.hw-phone\{[^}]*\}',
              '#hwp-app{--hw-bg:var(--bg);--hw-surface:var(--surface);--hw-ink:var(--ink);--hw-muted:var(--muted);--hw-line:var(--line);'
              '--hw-brand:var(--brand);--hw-onbrand:var(--onbrand);--hw-soft:var(--soft);--hw-scrim:var(--scrim)}', text, count=1)
text = re.sub(r'#hwp-app\{width:100%;font-family:[^}]*\}', '', text)
text = re.sub(r'#hwp-app \.hw-phone\{[^}]*\}\n?', '', text)
# Element-wide rules applied to the whole phone in the design; keep them off the reader and editor.
text = re.sub(r'#hwp-app (svg|button|input|select)\b', r'#hwp-app :is(.hw-screen,.hw-dialog) \1', text)
text = text.replace('#hwp-app *{box-sizing:border-box}\n', '').replace('#hwp-app [hidden]{display:none!important}\n', '')
header = ('/* Library, file-access intro and dialogs, ported from design/latest-inline-fragment.html (2026-10-18).\n'
          '   Generated by scripts/make_library_css.py; edit the overrides at the end of native.css instead. */\n')
open(out, 'w', encoding='utf-8', newline='\n').write(header + text.strip() + '\n')
print(len(kept), 'rules')
